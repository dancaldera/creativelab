/**
 * `MockAdapter` — a deterministic, network-free adapter.
 *
 * Used by the unit/contract suites and by the headless e2e driver, which commits the bytes
 * `fetchOutputs` produces as real project assets. That constrains the implementation:
 *   * `fetchOutputs` returns genuinely valid PNG and WAV bytes (see `bytes.ts`), not `"x"`;
 *   * every id, byte and cost is derived from a hash of the request, so two runs of the same
 *     request are byte-identical and e2e hashes are stable;
 *   * failure injection is explicit (`failFirstN`, `failWith`) and never leaks into other
 *     calls.
 *
 * Failure scenarios used by the contract suite can be injected three ways: `failWith` for
 * the submit path, `malformedResponses` for the catalog path, and `requireCredentials` for
 * the credential path.
 */
import {
  CredentialError,
  ProviderError,
  classifyHttpStatus,
  nextBackoffDelay,
  type CreativeLabError,
  type Spend,
} from "@creativelab/core";
import { billableUnits, costFromPricing } from "../cost.js";
import type { ProviderAdapter, ProviderContext } from "../adapter.js";
import { credentialErrorFromResponse, normalizeProviderError, submissionError } from "../errors.js";
import { capabilitiesFrom, type ModelCapabilities, type ModelDescriptor } from "../capabilities.js";
import type {
  GenerationRequest,
  Issue,
  JobStatusResult,
  RemoteOutput,
  SubmitResult,
  ValidationResult,
} from "../requests.js";
import { validateRequest } from "../validate.js";
import { assertOutputsFresh } from "../remote.js";
import { encodePng, encodeText, encodeVideoBlob, encodeWav } from "./bytes.js";

export interface MockAdapterOptions {
  /** Artificial delay applied to every call. Defaults to 0 so tests stay fast. */
  readonly latencyMs?: number;
  /** Fail the first N submissions with `failWith`, then succeed. */
  readonly failFirstN?: number;
  /** How the injected failure looks. Defaults to a retryable 500. */
  readonly failWith?: {
    status?: number;
    message?: string;
    category?: CreativeLabError["category"];
    retryable?: boolean;
    uncertain?: boolean;
  };
  /** Seed the generated bytes; two different seeds produce different output. */
  readonly seedOutputs?: number;
  /** Injectable clock. */
  readonly now?: () => Date;
  /** Retries after the first failed attempt, mirroring the REST adapters' policy. */
  readonly maxRetries?: number;
  /** Test seam: replaces the real timer so retry backoff is instantaneous. */
  readonly sleep?: (ms: number) => Promise<void>;
  /** Number of `getJob` calls before the job reports `completed`. Defaults to 1. */
  readonly pollsBeforeCompletion?: number;
  /**
   * When true the adapter behaves like a keyed provider: an absent credential raises a
   * `CredentialError`, and a vault value of `REJECTED` produces a 401-style failure.
   */
  readonly requireCredentials?: boolean;
  /** Return a malformed catalog body, to exercise the ProviderError path. */
  readonly malformedResponses?: boolean;
  /**
   * Injectable failure hook; receives the call name. Return an Error to fail that call.
   * A returned plain `Error` is typed by `interceptStatus` so the retry policy can reason
   * about it exactly as it would about a real HTTP failure.
   */
  readonly intercept?: (call: string, url: string) => Error | undefined;
  /** HTTP status attributed to an injected plain `Error`. Defaults to 500. */
  readonly interceptStatus?: number;
  /**
   * Override the expiry attached to generated outputs. Contract tests use a past timestamp
   * to prove `fetchOutputs` rejects an expired URL; the default is one hour ahead.
   */
  readonly expiresAt?: string;
}

interface MockJobRecord {
  readonly providerJobId: string;
  readonly request: GenerationRequest;
  readonly outputs: RemoteOutput[];
  readonly cost: Spend | null;
  polls: number;
  status: "running" | "completed" | "canceled";
}

const MOCK_PROVIDER_ID = "mock";
const MOCK_PROVIDER_LABEL = "Mock Provider (deterministic)";

/** Deterministic FNV-1a hash, used for ids, seeds and byte payloads. */
export function fnv1a(input: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

